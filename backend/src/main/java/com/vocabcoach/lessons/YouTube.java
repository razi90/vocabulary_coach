package com.vocabcoach.lessons;

import com.vocabcoach.UserError;
import com.vocabcoach.config.AppProperties;
import java.io.IOException;
import java.net.ProxySelector;
import java.net.URI;
import java.net.URLEncoder;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;
import org.springframework.web.util.HtmlUtils;
import tools.jackson.core.JacksonException;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * Everything the coach needs from YouTube.
 *
 * <ul>
 *   <li>{@link #search} - the official YouTube Data API. Needs YOUTUBE_API_KEY;
 *       without it the coach can only use URLs the learner pastes.</li>
 *   <li>{@link #verify} - oEmbed: does the video exist and may it be embedded?</li>
 *   <li>{@link #transcript} - the subtitles, read from the public watch page.
 *       There is no official way to read someone else's subtitles, so this is
 *       best effort: if YouTube changes the page or withholds the tracks, it
 *       returns empty and the coach sets an open listening task instead.</li>
 * </ul>
 */
@Component
public class YouTube {

  private static final Logger log = LoggerFactory.getLogger(YouTube.class);
  private static final String API = "https://www.googleapis.com/youtube/v3/";
  static final Set<String> DURATIONS = Set.of("short", "medium", "long");

  public record Video(String videoId, String title, String channel, String duration, long seconds,
                      boolean hasCaptions, String audioLanguage, String description) {}

  public record Transcript(String language, boolean autoGenerated, String text) {}

  private final String apiKey;
  private final JsonMapper json;
  private final HttpClient http = HttpClient.newBuilder()
      .connectTimeout(Duration.ofSeconds(8))
      .followRedirects(HttpClient.Redirect.NORMAL)
      .proxy(ProxySelector.getDefault())
      .build();

  public YouTube(AppProperties props, JsonMapper json) {
    this.apiKey = props.youtubeApiKey() == null ? "" : props.youtubeApiKey().trim();
    this.json = json;
  }

  public boolean searchAvailable() {
    return !apiKey.isEmpty();
  }

  // ---------- Search (YouTube Data API v3) ----------

  /**
   * Embeddable Spanish videos for a query. A search costs 100 of the 10 000
   * free quota units per day, the detail lookup 1.
   */
  public List<Video> search(String query, String duration, boolean onlyWithCaptions, int max) {
    if (!searchAvailable()) {
      throw new UserError("Die Videosuche ist auf diesem Server nicht eingerichtet (YOUTUBE_API_KEY fehlt).");
    }
    if (query == null || query.isBlank()) throw new UserError("query fehlt.");
    String length = duration != null && DURATIONS.contains(duration) ? duration : "medium";
    String searchUrl = API + "search?part=snippet&type=video&videoEmbeddable=true&relevanceLanguage=es"
        + "&safeSearch=strict&videoDuration=" + length + (onlyWithCaptions ? "&videoCaption=closedCaption" : "")
        + "&maxResults=" + Math.max(1, Math.min(max, 10)) + "&q=" + enc(query) + "&key=" + enc(apiKey);
    List<String> ids = new ArrayList<>();
    for (JsonNode item : apiGet(searchUrl).path("items")) {
      String id = item.path("id").path("videoId").asString("");
      if (!id.isEmpty()) ids.add(id);
    }
    if (ids.isEmpty()) return List.of();
    JsonNode details = apiGet(API + "videos?part=snippet,contentDetails&id=" + String.join(",", ids)
        + "&key=" + enc(apiKey));
    return parseVideos(details);
  }

  static List<Video> parseVideos(JsonNode details) {
    List<Video> out = new ArrayList<>();
    for (JsonNode v : details.path("items")) {
      JsonNode s = v.path("snippet");
      JsonNode c = v.path("contentDetails");
      long seconds = seconds(c.path("duration").asString(""));
      String description = s.path("description").asString("");
      out.add(new Video(v.path("id").asString(), s.path("title").asString(""), s.path("channelTitle").asString(""),
          clock(seconds), seconds, "true".equals(c.path("caption").asString("")),
          s.path("defaultAudioLanguage").asString(s.path("defaultLanguage").asString("")),
          description.length() > 300 ? description.substring(0, 300) + "…" : description));
    }
    return out;
  }

  private JsonNode apiGet(String url) {
    HttpResponse<String> res = get(url, "YouTube");
    JsonNode body = parse(res.body());
    if (res.statusCode() >= 400) {
      String reason = body.path("error").path("errors").path(0).path("reason").asString("");
      if ("quotaExceeded".equals(reason) || "dailyLimitExceeded".equals(reason)) {
        throw new UserError("Das Tageskontingent der YouTube-Suche ist aufgebraucht. Morgen geht es wieder, "
            + "bis dahin nur mit einer URL vom Lernenden.");
      }
      throw new UserError("Die YouTube-Suche ist fehlgeschlagen (" + res.statusCode() + " "
          + body.path("error").path("message").asString(reason) + ").");
    }
    return body;
  }

  // ---------- Exists and embeddable? (oEmbed) ----------

  public Map<String, String> verify(String videoId) {
    String watch = "https://www.youtube.com/watch?v=" + videoId;
    HttpResponse<String> res = get("https://www.youtube.com/oembed?url=" + enc(watch) + "&format=json", "YouTube");
    int code = res.statusCode();
    if (code == 400 || code == 401 || code == 403 || code == 404) {
      throw new UserError("Das Video \"" + videoId + "\" gibt es nicht oder es lässt sich nicht einbetten. "
          + "Nimm nur IDs aus search_youtube oder aus einer URL des Lernenden - nie aus dem Gedächtnis.");
    }
    if (code < 200 || code >= 300) throw new UserError("YouTube antwortete mit " + code + ".");
    JsonNode data = parse(res.body());
    return Map.of("title", data.path("title").asString(""), "channel", data.path("author_name").asString(""));
  }

  // ---------- Subtitles (best effort) ----------

  public Optional<Transcript> transcript(String videoId) {
    try {
      HttpResponse<String> page = get("https://www.youtube.com/watch?v=" + enc(videoId) + "&hl=es", "YouTube");
      if (page.statusCode() != 200) return Optional.empty();
      Optional<JsonNode> track = pickTrack(captionTracks(page.body()));
      if (track.isEmpty()) return Optional.empty();
      String base = track.get().path("baseUrl").asString("");
      if (!base.startsWith("https://www.youtube.com/")) return Optional.empty();
      HttpResponse<String> captions = get(base + "&fmt=json3", "YouTube");
      if (captions.statusCode() != 200) return Optional.empty();
      String text = captionText(captions.body());
      if (text.isBlank()) return Optional.empty();
      return Optional.of(new Transcript(track.get().path("languageCode").asString(""),
          "asr".equals(track.get().path("kind").asString("")), text));
    } catch (UserError | JacksonException e) {
      log.info("Kein Transkript für {}: {}", videoId, e.getMessage());
      return Optional.empty();
    }
  }

  /** The captionTracks array embedded in the watch page's player data. */
  JsonNode captionTracks(String html) {
    int key = html.indexOf("\"captionTracks\":");
    if (key < 0) return json.createArrayNode();
    int start = html.indexOf('[', key);
    int end = matchingBracket(html, start);
    if (start < 0 || end < 0) return json.createArrayNode();
    return json.readTree(html.substring(start, end + 1));
  }

  /** Spanish, written by a person if possible, else YouTube's automatic one. */
  static Optional<JsonNode> pickTrack(JsonNode tracks) {
    JsonNode auto = null;
    for (JsonNode t : tracks) {
      if (!t.path("languageCode").asString("").startsWith("es")) continue;
      if (!"asr".equals(t.path("kind").asString(""))) return Optional.of(t);
      if (auto == null) auto = t;
    }
    return Optional.ofNullable(auto);
  }

  /** json3 (events → segs → utf8) or, as a fallback, the XML format. */
  String captionText(String body) {
    StringBuilder sb = new StringBuilder();
    String trimmed = body.stripLeading();
    if (trimmed.startsWith("{")) {
      for (JsonNode event : json.readTree(trimmed).path("events")) {
        StringBuilder line = new StringBuilder();
        for (JsonNode seg : event.path("segs")) line.append(seg.path("utf8").asString(""));
        String l = line.toString().replace('\n', ' ').trim();
        if (!l.isEmpty()) sb.append(l).append('\n');
      }
    } else {
      Matcher m = Pattern.compile("<text[^>]*>(.*?)</text>", Pattern.DOTALL).matcher(trimmed);
      while (m.find()) {
        String l = HtmlUtils.htmlUnescape(HtmlUtils.htmlUnescape(m.group(1))).replace('\n', ' ').trim();
        if (!l.isEmpty()) sb.append(l).append('\n');
      }
    }
    return sb.toString().trim();
  }

  // ---------- Helpers ----------

  private HttpResponse<String> get(String url, String what) {
    HttpRequest req = HttpRequest.newBuilder(URI.create(url)).timeout(Duration.ofSeconds(10))
        .header("Accept-Language", "es-ES,es;q=0.9")
        .GET().build();
    try {
      return http.send(req, HttpResponse.BodyHandlers.ofString());
    } catch (InterruptedException e) {
      Thread.currentThread().interrupt();
      throw new UserError(what + "-Anfrage abgebrochen.");
    } catch (IOException e) {
      throw new UserError(what + " war nicht erreichbar (" + e.getMessage() + "). Später erneut versuchen.");
    }
  }

  private JsonNode parse(String body) {
    try {
      return body == null || body.isBlank() ? json.createObjectNode() : json.readTree(body);
    } catch (JacksonException e) {
      return json.createObjectNode();
    }
  }

  static long seconds(String isoDuration) {
    try {
      return Duration.parse(isoDuration).getSeconds();
    } catch (RuntimeException e) {
      return 0;
    }
  }

  static String clock(long seconds) {
    return seconds >= 3600
        ? String.format("%d:%02d:%02d", seconds / 3600, seconds % 3600 / 60, seconds % 60)
        : String.format("%d:%02d", seconds / 60, seconds % 60);
  }

  /** Index of the bracket closing the one at {@code start}, aware of JSON strings. */
  static int matchingBracket(String s, int start) {
    if (start < 0) return -1;
    int depth = 0;
    boolean inString = false;
    for (int i = start; i < s.length(); i++) {
      char c = s.charAt(i);
      if (inString) {
        if (c == '\\') i++;
        else if (c == '"') inString = false;
      } else if (c == '"') {
        inString = true;
      } else if (c == '[' || c == '{') {
        depth++;
      } else if (c == ']' || c == '}') {
        if (--depth == 0) return i;
      }
    }
    return -1;
  }

  private static String enc(String s) {
    return URLEncoder.encode(s, StandardCharsets.UTF_8);
  }

  /** For tool output: a video as a small map. */
  public static Map<String, Object> describe(Video v) {
    Map<String, Object> m = new LinkedHashMap<>();
    m.put("videoId", v.videoId());
    m.put("titel", v.title());
    m.put("kanal", v.channel());
    m.put("dauer", v.duration());
    m.put("untertitel", v.hasCaptions() ? "ja" : "unbekannt");
    if (!v.audioLanguage().isEmpty()) m.put("sprache", v.audioLanguage());
    m.put("beschreibung", v.description());
    return m;
  }
}
